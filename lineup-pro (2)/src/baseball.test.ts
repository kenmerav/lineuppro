test('middle school batting defaults to nine while Little League keeps the full order', () => {
  const battingOrder = Array.from({ length: 12 }, (_, index) => `p${index + 1}`);
  const firstInning: InningAssignments = { dugout: [] };
  getAllPositions(baseball).forEach((position, index) => {
    firstInning[position] = `p${index + 1}`;
  });
  firstInning.DH = 'p10';
  firstInning.EH = 'p11';
  const assignments: DefenseAssignments = { innings: 7, byInning: { 1: firstInning } };

  assert.deepEqual(getBattingLineupIds(battingOrder, baseball, assignments), battingOrder.slice(0, 9));
  assert.deepEqual(getBattingLineupIds(battingOrder, DEFAULT_SETTINGS, assignments), battingOrder);
  assert.deepEqual(
    getBattingLineupIds(battingOrder, { ...baseball, battingCount: 10 }, assignments),
    battingOrder.slice(0, 10),
  );
  assert.deepEqual(
    getBattingLineupIds(battingOrder, { ...baseball, battingCount: 12 }, assignments),
    battingOrder.slice(0, 11),
  );
});

