const baseball: Settings = { ...DEFAULT_SETTINGS, sport: 'baseball' };

test('team types present baseball as the middle school workflow', () => {
  assert.deepEqual(TEAM_TYPES, [
    { value: 'baseball', label: 'Middle School Baseball' },
    { value: 'softball', label: 'Little League' },
  ]);
  assert.equal(getTeamTypeLabel('baseball'), 'Middle School Baseball');
  assert.equal(getTeamTypeLabel(undefined), 'Little League');
  assert.deepEqual(getTeamTypeDefaults('baseball'), {
    sport: 'baseball',
    battingFormat: 'standard',
    battingCount: 9,
    inningsCount: 7,
    allowSamePositionBackToBack: true,
    preventDuplicatePositionInGame: false,
    requireEarlyInfieldByInning3: false,
  });
});

test('middle school baseball generates one stable defensive lineup', () => {
  const players = Array.from({ length: 11 }, (_, index) => ({
    id: `p${index + 1}`,
    name: `Player ${index + 1}`,
    color: '#000000',
  }));
  const settings: Settings = { ...baseball, inningsCount: 7 };
  const assignments = autoGenerateDefense(players, 7, settings);
  const firstInning = assignments.byInning[1];

  assert.equal(getAllPositions(settings).filter((position) => firstInning[position]).length, 9);
  assert.equal(firstInning.dugout.length, 2);
  for (let inning = 2; inning <= 7; inning++) {
    assert.deepEqual(assignments.byInning[inning], firstInning);
  }
  assert.deepEqual(validateAll(assignments, players, settings), { errors: [], warnings: [] });
});

