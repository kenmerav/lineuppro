test('defense assignment initializes a blank middle school lineup', () => {
  const assignments = { innings: 7, byInning: {} };
  const updated = assignPlayerToDefense(
    assignments,
    getAllPositions(baseball),
    1,
    'C',
    'one',
    true,
    true,
  );

  assert.deepEqual(assignments.byInning, {});
  for (let inning = 1; inning <= assignments.innings; inning++) {
    assert.equal(updated.byInning[inning].C, 'one');
    assert.deepEqual(updated.byInning[inning].dugout, []);
  }
});

