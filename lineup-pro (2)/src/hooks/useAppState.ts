import { useState, useEffect, useCallback, useMemo, useRef } from "react";
import { Player, DefenseAssignments, Settings, SavedGame, TeamBranding, GameLog } from "../types";
import { BATTING_ONLY_POSITIONS, DEFAULT_SETTINGS, PLAYER_COLORS } from "../constants";
import { autoGenerateDefense } from "../utils";
import {
  createOfflineTeamState,
  readOfflineTeamState,
  writeOfflineTeamState,
  type OfflineTeamState,
  type OfflineTeamStateInput,
} from "../offlineState";

export type SyncStatus = "saved" | "saving" | "offline";

const syncBattingOrderWithActivePlayers = (currentOrder: string[], roster: Player[]) => {
  const activeIds = new Set(roster.filter((player) => player.active !== false).map((player) => player.id));
  const nextOrder = currentOrder.filter((playerId) => activeIds.has(playerId));
  const existingIds = new Set(nextOrder);

  roster.forEach((player) => {
    if (player.active !== false && !existingIds.has(player.id)) {
      nextOrder.push(player.id);
    }
  });

  return nextOrder;
};

const sameOrder = (left: string[], right: string[]) =>
  left.length === right.length && left.every((value, index) => value === right[index]);

const sanitizeInningsCount = (inningsCount: number) =>
  Math.max(1, Math.floor(Number.isFinite(inningsCount) ? inningsCount : DEFAULT_SETTINGS.inningsCount));

const resizeAssignments = (currentAssignments: DefenseAssignments, inningsCount: number): DefenseAssignments => {
  const safeInningsCount = sanitizeInningsCount(inningsCount);
  const nextByInning: DefenseAssignments["byInning"] = {};

  Object.entries(currentAssignments.byInning || {}).forEach(([inningKey, inningValue]) => {
    const inningNumber = Number(inningKey);
    if (!Number.isFinite(inningNumber) || !inningValue) return;
    nextByInning[inningNumber] = {
      ...inningValue,
      dugout: [...(inningValue.dugout || [])],
    };
  });

  for (let inning = 1; inning <= safeInningsCount; inning++) {
    const existing = currentAssignments.byInning[inning];
    nextByInning[inning] = existing ? { ...existing, dugout: [...(existing.dugout || [])] } : { dugout: [] };
  }

  return {
    innings: safeInningsCount,
    byInning: nextByInning,
  };
};

export function useAppState(teamId?: string) {
  const [players, setPlayers] = useState<Player[]>([]);
  const [battingOrder, setBattingOrder] = useState<string[]>([]);
  const [assignments, setAssignments] = useState<DefenseAssignments>({
    innings: DEFAULT_SETTINGS.inningsCount,
    byInning: {}
  });
  const [settings, setSettings] = useState<Settings>(DEFAULT_SETTINGS);
  const [branding, setBranding] = useState<TeamBranding>({ teamName: "My Team" });
  const [savedGames, setSavedGames] = useState<SavedGame[]>([]);
  const [activeGameId, setActiveGameId] = useState<string | null>(null);
  const [masterRoster, setMasterRoster] = useState<Player[]>([]);
  const [gameLog, setGameLog] = useState<GameLog | undefined>(undefined);
  const [loading, setLoading] = useState(!!teamId);
  const [hasHydratedTeam, setHasHydratedTeam] = useState(!teamId);
  const [isOnline, setIsOnline] = useState(() => typeof navigator === "undefined" || navigator.onLine);
  const [syncStatus, setSyncStatus] = useState<SyncStatus>(isOnline ? "saved" : "offline");
  const initialSnapshotPendingRef = useRef(false);
  const hasPersistedInitialSnapshotRef = useRef(false);
  const snapshotRevisionRef = useRef(0);

  useEffect(() => {
    setHasHydratedTeam(!teamId);
    hasPersistedInitialSnapshotRef.current = false;
  }, [teamId]);

  useEffect(() => {
    const handleOnline = () => {
      setIsOnline(true);
      setSyncStatus("saving");
    };
    const handleOffline = () => {
      setIsOnline(false);
      setSyncStatus("offline");
    };
    window.addEventListener("online", handleOnline);
    window.addEventListener("offline", handleOffline);
    return () => {
      window.removeEventListener("online", handleOnline);
      window.removeEventListener("offline", handleOffline);
    };
  }, []);

  // Fetch team data
  useEffect(() => {
    if (!teamId) return;

    const applySnapshot = (snapshot: OfflineTeamState) => {
      setPlayers(snapshot.players);
      setBattingOrder(snapshot.battingOrder);
      setAssignments(snapshot.assignments);
      setSettings({ ...DEFAULT_SETTINGS, ...snapshot.settings });
      setBranding(snapshot.branding);
      setSavedGames(snapshot.savedGames);
      setActiveGameId(snapshot.activeGameId);
      setMasterRoster(snapshot.masterRoster);
      setGameLog(snapshot.gameLog);
    };

    const fetchTeam = async () => {
      setLoading(true);
      const cached = readOfflineTeamState(teamId);
      if (cached) {
        applySnapshot(cached);
        initialSnapshotPendingRef.current = cached.pendingSync;
        setHasHydratedTeam(true);
        setLoading(false);
        setSyncStatus(isOnline ? (cached.pendingSync ? "saving" : "saved") : "offline");
      }

      try {
        const res = await fetch("/api/teams");
        if (!res.ok) throw new Error("Failed to load teams.");
        const teams = await res.json();
        const team = teams.find((t: any) => t.id === teamId);
        if (!team) throw new Error("Team was not found.");

        const gamesRes = await fetch(`/api/teams/${teamId}/games`);
        if (!gamesRes.ok) throw new Error("Failed to load games.");
        const games = await gamesRes.json();

        const draftRes = await fetch(`/api/teams/${teamId}/draft`);
        if (!draftRes.ok) throw new Error("Failed to load the working game.");
        const draft = await draftRes.json();

        const latestCached = readOfflineTeamState(teamId);
        if (!cached?.pendingSync && !latestCached?.pendingSync) {
          const roster = Array.isArray(team.roster) ? team.roster : [];
          const serverSnapshot = createOfflineTeamState({
            branding: team.branding || { teamName: team.name || "My Team" },
            settings: { ...DEFAULT_SETTINGS, ...(team.settings || {}), ...(draft?.settings || {}) },
            masterRoster: roster,
            players: Array.isArray(draft?.players) && draft.players.length > 0 ? draft.players : roster,
            battingOrder: Array.isArray(draft?.battingOrder) && draft.battingOrder.length > 0
              ? draft.battingOrder
              : roster.map((player: Player) => player.id),
            assignments: draft?.assignments || resizeAssignments({ innings: 0, byInning: {} }, team.settings?.inningsCount || DEFAULT_SETTINGS.inningsCount),
            savedGames: games,
            activeGameId: cached?.activeGameId && games.some((game: SavedGame) => game.id === cached.activeGameId)
              ? cached.activeGameId
              : null,
            gameLog: draft?.log,
          }, false);
          hasPersistedInitialSnapshotRef.current = false;
          initialSnapshotPendingRef.current = false;
          applySnapshot(serverSnapshot);
          writeOfflineTeamState(teamId, serverSnapshot);
          setSyncStatus("saved");
        }
      } catch (e) {
        console.error("Failed to load team", e);
        setSyncStatus("offline");
      } finally {
        setLoading(false);
        setHasHydratedTeam(true);
      }
    };

    fetchTeam();
  }, [teamId, isOnline]);

  const offlineSnapshotInput = useMemo<OfflineTeamStateInput>(() => ({
    players,
    battingOrder,
    assignments,
    settings,
    branding,
    savedGames,
    activeGameId,
    masterRoster,
    gameLog,
  }), [players, battingOrder, assignments, settings, branding, savedGames, activeGameId, masterRoster, gameLog]);
  const latestSnapshotInputRef = useRef(offlineSnapshotInput);
  latestSnapshotInputRef.current = offlineSnapshotInput;

  useEffect(() => {
    if (!teamId || !hasHydratedTeam) return;
    const isInitialWrite = !hasPersistedInitialSnapshotRef.current;
    const pendingSync = isInitialWrite ? initialSnapshotPendingRef.current : true;
    hasPersistedInitialSnapshotRef.current = true;
    snapshotRevisionRef.current += 1;
    writeOfflineTeamState(teamId, createOfflineTeamState(offlineSnapshotInput, pendingSync));
    if (!isInitialWrite) setSyncStatus(isOnline ? "saving" : "offline");
  }, [teamId, hasHydratedTeam, isOnline, offlineSnapshotInput]);

  const markSnapshotSynced = useCallback((revision: number) => {
    if (!teamId || revision !== snapshotRevisionRef.current) return;
    writeOfflineTeamState(teamId, createOfflineTeamState(latestSnapshotInputRef.current, false));
    initialSnapshotPendingRef.current = false;
    setSyncStatus("saved");
  }, [teamId]);

  // Save team settings/roster when they change
  const saveTeamState = useCallback(async () => {
    if (!teamId || !isOnline) return;
    try {
      await fetch(`/api/teams/${teamId}`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: branding.teamName,
          branding,
          settings,
          roster: masterRoster
        })
      });
    } catch (e) {
      console.error("Failed to save team state", e);
    }
  }, [teamId, isOnline, branding, settings, masterRoster]);

  // Auto-save team state on changes (debounced or just on specific actions)
  // For now, let's call it manually or on specific updates

  const saveAsMasterRoster = useCallback(() => {
    setMasterRoster(players);
    // Trigger save
  }, [players]);

  useEffect(() => {
    if (!teamId || !hasHydratedTeam) return;
    saveTeamState();
  }, [teamId, hasHydratedTeam, masterRoster, settings, branding, saveTeamState]);

  const saveDraftState = useCallback(async () => {
    if (!teamId || !isOnline) return;
    const revision = snapshotRevisionRef.current;
    try {
      const response = await fetch(`/api/teams/${teamId}/draft`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          players,
          battingOrder,
          assignments,
          settings,
          branding,
          log: gameLog
        })
      });
      if (!response.ok) throw new Error("Failed to save working draft.");
      markSnapshotSynced(revision);
    } catch (e) {
      console.error("Failed to save working draft", e);
      setSyncStatus("offline");
    }
  }, [teamId, isOnline, players, battingOrder, assignments, settings, branding, gameLog, markSnapshotSynced]);

  useEffect(() => {
    if (!teamId || !hasHydratedTeam) return;
    const timer = setTimeout(() => {
      saveDraftState();
    }, 600);
    return () => clearTimeout(timer);
  }, [teamId, hasHydratedTeam, isOnline, players, battingOrder, assignments, settings, branding, savedGames, gameLog, saveDraftState]);

  const loadMasterRoster = useCallback(() => {
    if (masterRoster.length > 0) {
      setPlayers(masterRoster);
      setBattingOrder(masterRoster.map(p => p.id));
    }
  }, [masterRoster]);

  useEffect(() => {
    setBattingOrder((prev) => {
      const next = syncBattingOrderWithActivePlayers(prev, players);
      return sameOrder(prev, next) ? prev : next;
    });
  }, [players]);

  useEffect(() => {
    setAssignments((prev) => {
      if (prev.innings === settings.inningsCount) return prev;
      return resizeAssignments(prev, settings.inningsCount);
    });
  }, [settings.inningsCount]);

  const updateInningsCount = useCallback((inningsCount: number) => {
    const safeInningsCount = sanitizeInningsCount(inningsCount);
    setSettings((prev) => (
      prev.inningsCount === safeInningsCount
        ? prev
        : { ...prev, inningsCount: safeInningsCount }
    ));
    setAssignments((prev) => (
      prev.innings === safeInningsCount
        ? prev
        : resizeAssignments(prev, safeInningsCount)
    ));
  }, []);

  const startNewGame = useCallback((keepRoster: boolean = true) => {
    if (!keepRoster) {
      setPlayers([]);
      setBattingOrder([]);
    }
    setAssignments(resizeAssignments({ innings: 0, byInning: {} }, settings.inningsCount));
    setGameLog(undefined);
    setActiveGameId(null);
  }, [settings.inningsCount]);

  const addPlayer = useCallback((name: string, number?: string, grade?: Player["grade"]) => {
    const newPlayer: Player = {
      id: crypto.randomUUID(),
      name,
      number: number?.trim() || undefined,
      grade,
      color: PLAYER_COLORS[players.length % PLAYER_COLORS.length],
      active: true
    };
    setPlayers(prev => [...prev, newPlayer]);
    setMasterRoster(prev => [...prev, newPlayer]);
    setBattingOrder(prev => [...prev, newPlayer.id]);
  }, [players.length]);

  const bulkAddPlayers = useCallback((names: string) => {
    const newNames = names.split("\n").map(n => n.trim()).filter(n => n.length > 0);
    const newPlayers: Player[] = newNames.map((line, i) => {
      // Supports bulk lines like "12 Mike" or "Mike".
      const match = line.match(/^#?(\d+)\s+(.+)$/);
      const parsedNumber = match ? match[1] : undefined;
      const parsedName = match ? match[2].trim() : line;
      return {
        id: crypto.randomUUID(),
        name: parsedName,
        number: parsedNumber,
        color: PLAYER_COLORS[(players.length + i) % PLAYER_COLORS.length],
        active: true
      };
    });
    setPlayers(prev => [...prev, ...newPlayers]);
    setMasterRoster(prev => [...prev, ...newPlayers]);
    setBattingOrder(prev => [...prev, ...newPlayers.map(p => p.id)]);
  }, [players.length]);

  const updatePlayer = useCallback((id: string, updates: Partial<Player>) => {
    setPlayers(prev => prev.map(p => p.id === id ? { ...p, ...updates } : p));
    const { active, ...rosterUpdates } = updates;
    if (Object.keys(rosterUpdates).length > 0) {
      setMasterRoster(prev => prev.map(p => p.id === id ? { ...p, ...rosterUpdates } : p));
    }
    
    if (updates.active !== undefined) {
      setBattingOrder((prev) => {
        if (updates.active === false) {
          return prev.filter((playerId) => playerId !== id);
        }

        if (prev.includes(id)) return prev;
        return [...prev, id];
      });

      setGameLog(prev => {
        if (!prev) return prev;
        const next = { ...prev };
        next.playerStats = { ...next.playerStats };
        if (next.playerStats[id]) {
          next.playerStats[id] = { ...next.playerStats[id], played: updates.active };
        } else {
          next.playerStats[id] = { ab: 0, played: updates.active };
        }
        return next;
      });
    }
  }, []);

  const deletePlayer = useCallback((id: string) => {
    setPlayers(prev => prev.filter(p => p.id !== id));
    setMasterRoster(prev => prev.filter(p => p.id !== id));
    setBattingOrder(prev => prev.filter(pid => pid !== id));
    setAssignments(prev => {
      const next = { ...prev };
      for (let i = 1; i <= next.innings; i++) {
        const inning = { ...next.byInning[i] };
        Object.keys(inning).forEach(pos => {
          if (inning[pos] === id) delete inning[pos];
        });
        inning.dugout = inning.dugout.filter(pid => pid !== id);
        next.byInning[i] = inning;
      }
      return next;
    });
  }, []);

  const buildGamePayload = useCallback((meta: SavedGame["meta"]) => ({
    meta,
    players,
    batting_order: battingOrder,
    assignments,
    settings,
    branding,
    log: gameLog
  }), [players, battingOrder, assignments, settings, branding, gameLog]);

  const saveGame = useCallback(async (meta: SavedGame["meta"]) => {
    if (!teamId) {
      throw new Error("Team is required to save games.");
    }

    const res = await fetch(`/api/teams/${teamId}/games`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(buildGamePayload(meta))
    });
    if (!res.ok) {
      throw new Error("Failed to save game.");
    }

    const { id } = await res.json();
    const newGame: SavedGame = {
      id,
      meta,
      players,
      battingOrder,
      assignments,
      settings,
      branding,
      log: gameLog
    };
    setSavedGames(prev => [...prev, newGame]);
    setActiveGameId(id);
    return newGame;
  }, [teamId, buildGamePayload, players, battingOrder, assignments, settings, branding, gameLog]);

  const updateGame = useCallback(async (gameId: string, meta: SavedGame["meta"]) => {
    if (!teamId) {
      throw new Error("Team is required to update games.");
    }

    const res = await fetch(`/api/teams/${teamId}/games/${gameId}`, {
      method: "PUT",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(buildGamePayload(meta))
    });
    if (!res.ok) {
      throw new Error("Failed to update game.");
    }

    const updated = await res.json() as SavedGame;
    setSavedGames(prev => prev.map(g => g.id === gameId ? updated : g));
    setActiveGameId(updated.id);
    return updated;
  }, [teamId, buildGamePayload]);

  const activeGameMeta = savedGames.find((game) => game.id === activeGameId)?.meta;
  const activeGameMetaKey = activeGameMeta ? JSON.stringify(activeGameMeta) : "";

  useEffect(() => {
    if (!teamId || !hasHydratedTeam || !isOnline || !activeGameId || !activeGameMeta || !gameLog) return;

    const timer = setTimeout(async () => {
      try {
        const res = await fetch(`/api/teams/${teamId}/games/${activeGameId}`, {
          method: "PUT",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(buildGamePayload(activeGameMeta)),
        });
        if (!res.ok) throw new Error("Failed to auto-save the active game.");
        const updated = await res.json() as SavedGame;
        setSavedGames((current) => current.map((game) => game.id === activeGameId ? updated : game));
      } catch (error) {
        console.error("Failed to auto-save active game", error);
      }
    }, 700);

    return () => clearTimeout(timer);
  }, [teamId, hasHydratedTeam, isOnline, activeGameId, activeGameMetaKey, gameLog, buildGamePayload]);

  const deleteGame = useCallback(async (id: string) => {
    if (!teamId) {
      throw new Error("Team is required to delete games.");
    }

    const res = await fetch(`/api/teams/${teamId}/games/${id}`, {
      method: "DELETE"
    });
    if (!res.ok) {
      throw new Error("Failed to delete game.");
    }

    setSavedGames(prev => prev.filter(g => g.id !== id));
    setActiveGameId(prev => prev === id ? null : prev);
  }, [teamId]);

  const importGame = useCallback(async (game: SavedGame) => {
    if (!teamId) {
      throw new Error("Team is required to import games.");
    }

    const res = await fetch(`/api/teams/${teamId}/games`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        meta: game.meta,
        players: game.players,
        batting_order: game.battingOrder,
        assignments: game.assignments,
        settings: game.settings,
        branding: game.branding,
        log: game.log
      })
    });
    if (!res.ok) {
      throw new Error("Failed to import game.");
    }

    const { id } = await res.json();
    const imported = { ...game, id };
    setSavedGames(prev => [...prev, imported]);
    return imported;
  }, [teamId]);

  const loadGame = useCallback((game: SavedGame) => {
    setPlayers(game.players);
    setBattingOrder(game.battingOrder);
    setAssignments(game.assignments);
    setSettings({ ...DEFAULT_SETTINGS, ...(game.settings || {}) });
    setBranding(game.branding);
    setGameLog(game.log);
    setActiveGameId(game.id);
  }, []);

  const generateDefense = useCallback(() => {
    const firstInning = assignments.byInning[1] || { dugout: [] };
    const battingOnlyAssignments = settings.sport === "baseball"
      ? Object.fromEntries(BATTING_ONLY_POSITIONS
          .map((position) => [position, firstInning[position]])
          .filter((entry): entry is [string, string] => typeof entry[1] === "string"))
      : {};
    const battingOnlyPlayerIds = new Set(Object.values(battingOnlyAssignments));
    const activePlayers = players.filter(p => p.active !== false && !battingOnlyPlayerIds.has(p.id));
    const newAssignments = autoGenerateDefense(activePlayers, settings.inningsCount, settings, savedGames);
    if (settings.sport === "baseball") {
      for (let inning = 1; inning <= newAssignments.innings; inning++) {
        Object.assign(newAssignments.byInning[inning], battingOnlyAssignments);
      }
    }
    setAssignments(newAssignments);
  }, [players, assignments, settings, savedGames]);

  const updateBranding = useCallback((updates: Partial<TeamBranding>) => {
    setBranding(prev => ({ ...prev, ...updates }));
  }, []);

  return {
    players, setPlayers,
    battingOrder, setBattingOrder,
    assignments, setAssignments,
    settings, setSettings,
    updateInningsCount,
    branding, setBranding: updateBranding,
    savedGames, setSavedGames,
    gameLog, setGameLog,
    loading,
    syncStatus,
    activeGameId,
    addPlayer, bulkAddPlayers, updatePlayer, deletePlayer,
    saveGame, updateGame, loadGame, deleteGame, importGame, generateDefense,
    saveAsMasterRoster, loadMasterRoster, startNewGame
  };
}
